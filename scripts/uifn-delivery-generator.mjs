function pascal(value) {
  return value.split(/[-_]/).map((part) => part ? `${part[0].toUpperCase()}${part.slice(1)}` : '').join('');
}

function stable(value) {
  return `${value.trimEnd()}\n`;
}

function walk(root, relative) {
  const pathname = path.join(root, relative);
  if (!existsSync(pathname)) return [];
  return readdirSync(pathname).flatMap((name) => {
    const child = path.join(relative, name);
    return statSync(path.join(root, child)).isDirectory() ? walk(root, child) : [child];
  });
}

