function componentCssVariables(css, primitiveId) {
  const variables = new Set([
    '--uifn-component-bg',
    '--uifn-component-bg-muted',
    '--uifn-component-fg',
    '--uifn-component-fg-muted',
    '--uifn-component-border',
    '--uifn-component-border-strong',
    '--uifn-component-accent',
    '--uifn-component-accent-contrast',
    '--uifn-component-danger',
    '--uifn-component-shadow',
    '--uifn-component-radius-sm',
    '--uifn-component-radius-md',
    '--uifn-component-radius-lg',
    '--uifn-control-block-size',
    '--uifn-control-gap',
  ]);
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!match[1].includes(`[data-uifn-component="${primitiveId}"]`)) continue;
    for (const variable of match[2].match(/--uifn-[a-z0-9-]+/g) ?? []) variables.add(variable);
  }
  return [...variables].sort().map((name) => ({
    name,
    scope: name.startsWith(`--uifn-${primitiveId}`) ? 'component' : 'shared',
  }));
}

function dataAttributeRecords(primitive) {
  const records = [
    { name: 'data-uifn-component', value: primitive.id, parts: 'all styled parts', stability: 'stable' },
    { name: 'data-uifn-part', value: primitive.anatomy.map((part) => part.id).join(' | '), parts: 'all styled parts', stability: 'stable' },
    { name: 'data-state', value: primitive.states.map((state) => state.name).join(' | '), parts: 'stateful parts', stability: 'stable semantic state' },
  ];
  for (const input of primitive.inputs) {
    if (['disabled', 'invalid', 'readOnly', 'orientation', 'dir'].includes(input.name)) {
      records.push({
        name: `data-${input.name === 'readOnly' ? 'readonly' : input.name}`,
        value: input.type === 'boolean' ? 'true | false' : input.type,
        parts: 'parts whose semantics depend on this input',
        stability: 'stable semantic state',
      });
    }
  }
  return records;
}

