export function materializeOutputs(root, outputs, options = {}) {
  const mode = options.mode ?? 'check';
  const errorCode = options.errorCode ?? 'UIFN_GENERATED_SOURCE_DRIFT';
  const managedRoots = options.managedRoots ?? [];
  if (mode === 'write') {
    for (const relative of managedRoots) rmSync(path.join(root, relative), { recursive: true, force: true });
  }
  const failures = [];
  for (const [relative, contents] of Object.entries(outputs).sort(([left], [right]) => left.localeCompare(right))) {
    const pathname = path.join(root, relative);
    if (mode === 'check') {
      let current = '';
      try { current = readFileSync(pathname, 'utf8'); } catch {}
      if (current !== contents) failures.push({ code: errorCode, path: relative });
    } else {
      mkdirSync(path.dirname(pathname), { recursive: true });
      writeFileSync(pathname, contents);
    }
  }
  if (mode === 'check') {
    const expected = new Set(Object.keys(outputs));
    for (const managedRoot of managedRoots) {
      for (const relative of walk(root, managedRoot)) {
        if (!expected.has(relative)) failures.push({ code: errorCode, path: relative, reason: 'unexpected-output' });
      }
    }
  }
  return failures;
}
