function publicInputDefault(primitive, input) {
  const inputType = publicInputType(primitive, input);
  if (input.required) return 'required';
  const override = SEMANTIC_DEFAULT_OVERRIDES[`${primitive.id}.${input.name}`];
  if (override) return `undefined → ${override}`;
  if (input.name === 'open' || input.name === 'defaultOpen') return 'undefined → false';
  if (input.name === 'value' || input.name === 'inputValue') return 'undefined (uncontrolled)';
  if (input.name.startsWith('default')) {
    if (inputType.endsWith('[]')) return 'undefined → []';
    if (inputType === 'boolean' || inputType === 'boolean|string') return 'undefined → false';
    if (inputType === 'string') return 'undefined → ""';
    return 'undefined (component initial value)';
  }
  if (inputType === 'boolean') return 'undefined → false';
  if (input.name === 'dir' || input.name === 'direction') return 'undefined → "ltr"';
  if (input.name === 'locale') return 'undefined → environment locale';
  return 'undefined (no public prop override)';
}

function callbackName(changeEvent) {
  const stem = changeEvent.replace(/_CHANGE$/, '').toLowerCase().split('_').map(pascal).join('');
  return `on${stem}Change`;
}

function callbackRecords(primitive) {
  const inputsByName = new Map(primitive.inputs.map((input) => [input.name, input]));
  return (primitive.controlledModel?.changeEvents ?? [])
    .filter((event) => event !== 'NATIVE_CHANGE')
    .map((event, index) => {
      const valueName = primitive.controlledModel.valueInputs[index] ?? primitive.controlledModel.valueInputs[0] ?? 'value';
      const input = inputsByName.get(valueName);
      const valueType = input ? publicInputType(primitive, input) : 'unknown';
      return {
        name: callbackName(event),
        signature: `(value: ${valueType}) => void`,
        event,
        description: `Called after ${primitive.name} requests a ${valueName} change. Controlled consumers must commit the value back through ${valueName}.`,
      };
    });
}

