export function readCanonicalPrimitives(root) {
  const anatomy = JSON.parse(readFileSync(path.join(root, 'uifn/catalog/generated/anatomy-types.json'), 'utf8'));
  const catalog = JSON.parse(readFileSync(path.join(root, 'uifn/catalog/generated/catalog.json'), 'utf8'));
  const css = readFileSync(path.join(root, 'uifn/components/src/styles.css'), 'utf8');
  const primitives = catalog.primitives.map((primitive) => {
    const fixtureParts = componentPartRecords(primitive);
    const [fixtureRoot, ...fixtureChildren] = fixtureParts;
    return {
      id: primitive.id,
      name: primitive.name,
      inputs: primitive.inputs.map((input) => ({
        name: input.name,
        type: publicInputType(primitive, input),
        required: input.required,
        defaultValue: publicInputDefault(primitive, input),
        description: `${input.required ? 'Required' : 'Optional'} reactive ${input.name} input from the canonical ${primitive.name} contract.`,
      })),
      implementationKind: primitive.implementationKind,
      behaviorFamily: primitive.behaviorFamily,
      api: apiReference(primitive, css),
      parts: primitive.anatomy.map((part) => ({
        id: part.id,
        exportName: `${primitive.name}${pascal(part.id)}`,
        element: part.element,
        cardinality: part.cardinality,
      })),
      demo: {
        schemaVersion: 1,
        fixtureVersion: UIFN_COMPONENT_FIXTURE_VERSION,
        root: {
          id: fixtureRoot.id,
          exportName: fixtureRoot.exportName,
          element: fixtureRoot.element,
          voidElement: fixtureRoot.voidElement,
        },
        rootProps: catalogComponentRootProps(primitive),
        parts: fixtureChildren.map((part) => ({
          id: part.id,
          exportName: part.exportName,
          many: part.cardinality === 'many',
          element: part.element,
          voidElement: part.voidElement,
          parentId: part.parentId,
          value: part.value,
          repeat: part.repeat,
        })),
      },
    };
  });
  return { anatomy, primitives };
}

