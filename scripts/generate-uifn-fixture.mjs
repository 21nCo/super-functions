import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = readFileSync(new URL('../uifn/react/src/fixture.ts', import.meta.url), 'utf8');
const target = new URL('../uifn/registry/src/preset/fixture-source.ts', import.meta.url);
const expected = '// Generated by scripts/generate-uifn-fixture.mjs --write. Do not edit.\nexport const PRESET_REACT_FIXTURE_SOURCE = ' + JSON.stringify(source) + ';\n';
if (process.argv.includes('--write')) writeFileSync(target, expected);
else if (readFileSync(target, 'utf8') !== expected) throw new Error(`Regenerate ${fileURLToPath(target)} with --write`);
